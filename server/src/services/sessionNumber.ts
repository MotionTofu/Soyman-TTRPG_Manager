/**
 * Порядковый номер сессии внутри своей кампании.
 *
 * Номер нигде не хранится — он вычисляется. Раньше этот подзапрос был
 * скопирован в четыре роута (calendar, campaigns, links, sessions), и любая
 * правка обязана была попасть во все четыре; здесь он один.
 *
 * Отменённые игры идут отдельным счётом. Мастер считает сессии по сыгранному:
 * если седьмую отменили, следующая состоявшаяся — всё равно седьмая, а
 * отменённая получает собственный номер и зовётся «Отменённая №1». Иначе
 * отменённая съедала бы номер, и нумерация игр расходилась бы с тем, как о
 * них говорят за столом.
 *
 * Ничьи по дате разрешаются так же, как и прежде (`date <= s.date`): две игры
 * одного дня получают один номер. Поведение сохранено намеренно — менять его
 * здесь значило бы тихо переписать номера в уже существующих текстах.
 *
 * Подставляется как выражение в SELECT; внешняя таблица сессий обязана иметь
 * псевдоним `s`.
 */
export const SESSION_NUMBER_SQL = `
  (CASE WHEN s.status = 'cancelled'
        THEN (SELECT COUNT(*) FROM sessions s2
               WHERE s2.campaign_id = s.campaign_id
                 AND s2.archived_at IS NULL
                 AND s2.status = 'cancelled'
                 AND s2.date <= s.date)
        ELSE (SELECT COUNT(*) FROM sessions s2
               WHERE s2.campaign_id = s.campaign_id
                 AND s2.archived_at IS NULL
                 AND s2.status <> 'cancelled'
                 AND s2.date <= s.date)
   END)`;
