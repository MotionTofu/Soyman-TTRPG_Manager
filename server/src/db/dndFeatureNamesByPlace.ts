/** Возвращает число записанных имён. */
export function applyDndFeatureNamesByPlace(database: Database.Database): number {
  const upd = database.prepare(
    `UPDATE compendium_entries SET name_original = ?
     WHERE kind = 'feature' AND name_original = '' AND level = ? AND name = ?
       AND parent_id IN (SELECT id FROM compendium_entries WHERE name_original = ?)`
  );
  let changed = 0;
  database.transaction(() => {
    for (const [parent, level, ru, en] of DND_FEATURE_NAMES_BY_PLACE) changed += upd.run(en, level, ru, parent).changes;
  })();
  return changed;
}
