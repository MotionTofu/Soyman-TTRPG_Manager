/**
 * Сохранение изменённых полей вместо снимка целиком.
 *
 * Быстрые правки на листе (пипс, галочка, хиты) уходят через очередь с
 * дебаунсом 400 мс, и до сих пор каждая слала **весь** JSON чарника. Две
 * правки, сделанные в один и тот же дебаунс из разных окон, сводились к
 * «последний записавший выиграл»: чужое изменение соседнего поля исчезало
 * без следа, потому что снимок отправителя его не содержал.
 *
 * `contentPatch` — плоский объект верхнего уровня: ключи из него ложатся
 * поверх сохранённого, остальные остаются как есть. Вложенности нет
 * намеренно: правка внутри `spellsByLevel` шлёт этот массив целиком, и это
 * ровно та единица, которой человек оперирует. `null` в значении стирает
 * ключ — иначе поле, которое лист убрал, вернулось бы из сохранённого.
 */
export function mergeContentPatch(stored: string, patch: Record<string, unknown>): string {
  let base: Record<string, unknown>;
  try {
    const parsed = JSON.parse(stored || "{}");
    base = parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed : {};
  } catch {
    // Разобрать не вышло — сохранённое и так не читается листом; писать
    // поверх него патч честнее, чем отказывать в сохранении навсегда.
    base = {};
  }
  for (const [key, value] of Object.entries(patch)) {
    if (value === null) delete base[key];
    else base[key] = value;
  }
  return JSON.stringify(base);
}
