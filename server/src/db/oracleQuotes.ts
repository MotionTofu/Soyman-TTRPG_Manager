export function migrateClassOracleQuotes(database: Database): void {
  if (database.prepare("SELECT 1 FROM app_settings WHERE key = ?").get(MIGRATION_KEY)) return;
  const read = database.prepare("SELECT id, data FROM compendium_entries WHERE uid = ?");
  const update = database.prepare("UPDATE compendium_entries SET data = ? WHERE id = ?");
  let added = 0;
  for (const [uid, quotes] of POOLS) {
    const row = read.get(uid) as { id: number; data: string } | undefined;
    if (!row) continue;
    let data: Record<string, unknown>;
    try {
      data = JSON.parse(row.data || "{}");
    } catch {
      continue;
    }
    const have = Array.isArray(data.oracle_quotes) ? (data.oracle_quotes as unknown[]).filter((x): x is string => typeof x === "string") : [];
    const fresh = quotes.filter((x) => !have.includes(x));
    if (fresh.length === 0) continue;
    data.oracle_quotes = [...have, ...fresh];
    update.run(JSON.stringify(data), row.id);
    added += fresh.length;
  }
  if (added) console.log(`[migrate] ${MIGRATION_KEY}: цитат оракула добавлено ${added}`);
  database.prepare("INSERT OR REPLACE INTO app_settings (key, value) VALUES (?, ?)").run(MIGRATION_KEY, new Date().toISOString());
}
