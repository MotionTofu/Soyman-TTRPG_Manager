import { planSettingCrossLinks } from "../import/crossLinks";
const p = planSettingCrossLinks(1);
const on = p.filter((x) => x.suggested);
console.log(`находок: ${p.length}, отмечено сразу: ${on.length}`);
const byDoubt = new Map<string, number>();
for (const x of p) if (!x.suggested) byDoubt.set(x.doubt ?? "?", (byDoubt.get(x.doubt ?? "?") ?? 0) + 1);
console.log("не отмечено:", [...byDoubt].map(([d, c]) => `${d} ×${c}`).join(", "));
const byOwner = new Map<string, number>();
for (const x of p) byOwner.set(x.ownerLabel, (byOwner.get(x.ownerLabel) ?? 0) + 1);
console.log("по владельцам текста:", [...byOwner].map(([o, c]) => `${o} ×${c}`).join(", "));
console.log("\nотмеченные (первые 14):");
for (const x of on.slice(0, 14)) console.log(`  ${x.ownerLabel} «${x.ownerName}» · ${x.fieldLabel}: «${x.matched}» → ${x.targetName} (${x.via})`);
console.log("\nне отмеченные (первые 8):");
for (const x of p.filter((y) => !y.suggested).slice(0, 8)) console.log(`  ${x.ownerLabel} «${x.ownerName}»: «${x.matched}» → ${x.targetName} — ${x.doubt}`);
