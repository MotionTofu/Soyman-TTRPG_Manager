// Обработка декоративных изображений (дизайн-ревизия, см. design_revision.md §3).
//
// ЭТАЛОН. Тон `saturate(.88) contrast(1.04)` плюс зерно 3 px точкой поверх —
// то же, что стоит на портрете карты персонажа. До 2026-09-10 здесь жил
// дуотон в два полюса (--ink → --paper), он снят: решение владельца — сделать
// эталонной обработку с карты и заменить ею дуотон везде. Причина в том, что
// дуотон перекрашивал арт, а тон с зерном оставляет его собой и всё равно
// сшивает пять разных по стилистике картинок в один экран.
//
// ОБЛАСТЬ (§1.13, не изменилась). Обработка ложится на изображение-ФОН и
// никогда на изображение-СОДЕРЖИМОЕ. Карты локаций, галерея и лайтбокс
// остаются как загружены — обработанная карта это сломанная карта. Портрет на
// карте персонажа и аватар персонажа считаются фоном: это подложка под именем
// и костями, а не то, что открывают рассмотреть.
//
// Тумблер сквозной (как loadRadiusOverride/loadHideFinance), а не свойство
// режима: «не перекрашивай мои арты» — убеждение про свои картинки, оно не
// должно меняться от смены темы. Гасит тон и зерно эталона, а также растр
// (cover-halftone). Наклоны и фактуры самого интерфейса это отделка, а не
// чужие изображения, и остаются.

// Ключ хранилища ИСТОРИЧЕСКИЙ и переименованию не подлежит: это данные, а не
// имя. Переименовать его — значит либо потерять уже сохранённый выбор
// владельца, либо тащить миграцию ради красоты строки.
const KEY = "rpgManagerCoverDuotone";
const CHANGE_EVENT = "image-treatment-changed";

export function loadImageTreatment(): boolean {
  try {
    // По умолчанию включена: единство экрана — это то, ради чего она заведена.
    return localStorage.getItem(KEY) !== "0";
  } catch {
    return true;
  }
}

export function saveImageTreatment(on: boolean): void {
  try {
    if (on) localStorage.removeItem(KEY);
    else localStorage.setItem(KEY, "0");
  } catch {
    /* ignore */
  }
  applyImageTreatment();
  window.dispatchEvent(new Event(CHANGE_EVENT));
}

// Пишет флаг на <html>, а не пробрасывает пропсом через дерево: обработку
// применяет CSS ([data-image-treatment]), и переключение должно доходить до
// каждой картинки в приложении одним движением, включая уже отрисованные.
export function applyImageTreatment(): void {
  document.documentElement.toggleAttribute("data-image-treatment", loadImageTreatment());
}

export { CHANGE_EVENT as IMAGE_TREATMENT_EVENT };
