/**
 * Страницы, уже переведённые на слой данных (docs/adr/0001, п. 8).
 *
 * Правка в другом окне приходит сигналом (dataSync.ts). Переведённая страница
 * обновляет задетое сама, без перезагрузки (data/DataLayerSync.tsx), а
 * непереведённая умеет только перезагрузиться целиком. Пока перевод идёт
 * группами, окно перезагружается по сигналу, только если открытая в нём
 * страница отсюда не значится (решение владельца 2026-09-11).
 *
 * Список растёт с каждой переведённой группой; когда переведено всё, он и
 * перезагрузка по сигналу уходят вместе.
 */
const MIGRATED_ROUTES: readonly RegExp[] = [
  // Группа «лист персонажа»: профиль и чарник на весь экран.
  /^\/characters\/\d+\/?$/,
  /^\/characters\/\d+\/sheet\/?$/,
  // Группа «пульт и сессии»: профиль сессии, пульт и вынесенная панель пульта.
  // Окно показа игрокам (/live/show) сюда не входит — оно слушает сигналы само.
  /^\/sessions\/\d+\/?$/,
  /^\/sessions\/\d+\/live\/?$/,
  /^\/sessions\/\d+\/live\/panel\/[A-Za-z]+\/?$/,
  // Группа «сущности сеттинга», часть 1: девять карточек. Сеттинг — часть 2.
  /^\/locations\/\d+\/?$/,
  /^\/beings\/\d+\/?$/,
  /^\/artifacts\/\d+\/?$/,
  /^\/communities\/\d+\/?$/,
  /^\/events\/\d+\/?$/,
  /^\/compendium\/\d+\/?$/,
  /^\/scenes\/\d+\/?$/,
  /^\/adventures\/\d+\/?$/,
];

export function isMigratedRoute(pathname: string): boolean {
  return MIGRATED_ROUTES.some((re) => re.test(pathname));
}
