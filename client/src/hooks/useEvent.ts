import { useCallback, useLayoutEffect, useRef } from "react";

// Стабильная ссылка на обработчик, который всегда видит свежие пропсы.
//
// Зачем: карточка листа большая, и половина её узлов обёрнута в `memo`.
// Обработчик, пересобираемый на каждый рендер, ломает `memo` — один щелчок
// перерисовывает весь раздел. Обычный `useCallback([])` этого не допускает,
// но замыкает первые пропсы и потом врёт.
//
// Раньше это решалось «свежим рефом» — `ref.current = value` прямо в теле
// компонента. Запись во время рендера делает рендер нечистым: в StrictMode
// и при прерванном конкурентном рендере в реф уезжает значение прохода,
// который React выбросил. Здесь запись перенесена в `useLayoutEffect`, то
// есть в фазу коммита. Обработчики вызываются только после коммита, так что
// свежесть не страдает; вызывать результат во время рендера нельзя.
export function useEvent<A extends unknown[], R>(fn: (...args: A) => R): (...args: A) => R {
  const ref = useRef(fn);
  useLayoutEffect(() => {
    ref.current = fn;
  });
  return useCallback((...args: A) => ref.current(...args), []);
}

// Тот же приём для значения, а не для функции: реф, всегда хранящий последнее
// закоммиченное значение. Нужен там, где стабильный обработчик читает свежие
// пропсы не сразу, а после `await`, и разбирать его на два `useEvent` дороже,
// чем оставить чтение через реф. Запись — тоже в фазе коммита.
export function useLatest<T>(value: T): { readonly current: T } {
  const ref = useRef(value);
  useLayoutEffect(() => {
    ref.current = value;
  });
  return ref;
}
