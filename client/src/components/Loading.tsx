// Единственный экран ожидания в приложении. Раньше на его месте стояли
// разрозненные «Загрузка…» и один самодельный крутящийся кружок.
//
// Задержка перед появлением — 400 мс, и она сделана чистым CSS
// (animation-delay + opacity: 0 в нулевом кадре), а не таймером в React.
// Причина в том, что почти все места ожидания здесь ждут useCurrentUser, то
// есть локальные миллисекунды: с мгновенным показом это была бы вспышка на
// каждом переходе. Таймер на useState дал бы тот же результат ценой лишнего
// рендера и уборки в useEffect — CSS справляется без состояния вообще.
//
// 400 мс — не выдуманное число: столько же ждёт splash в electron/main.js,
// то есть порог «пора показать, что мы живы» в проекте уже выбран.
import { SoyMan } from "./SoyMan";

export function Loading({
  label = "Загрузка…",
  full = false,
}: {
  /** Что именно грузится, если это не очевидно из соседнего текста. */
  label?: string;
  /** true — занять всю высоту родителя и встать по центру (маршруты, Suspense). */
  full?: boolean;
}) {
  return (
    <div className={full ? "soy-loading soy-loading--full" : "soy-loading"}>
      {/* decorative: подпись рядом говорит то же самое, дублировать её
          для скринридера незачем. Роль «идёт загрузка» несёт role="status". */}
      <SoyMan state="working" size="md" decorative />
      <p className="muted" role="status">
        {label}
      </p>
    </div>
  );
}
