// Английские имена — на случай переустановленного модуля с латинскими типами.
const ALIASES: Record<string, string> = {
  aberration: "Аберрация",
  beast: "Зверь",
  celestial: "Небожитель",
  construct: "Конструкт",
  dragon: "Дракон",
  elemental: "Элементаль",
  fey: "Фея",
  fiend: "Исчадие",
  giant: "Великан",
  humanoid: "Гуманоид",
  monstrosity: "Чудовище",
  ooze: "Студень",
  plant: "Растение",
  undead: "Нежить",
};

function normType(raw: string): string {
  return raw.trim().toLowerCase().replace(/ё/g, "е");
}

/** Тип существа записи бестиария. `creature_type` лежит объектом
 *  `MechanicsOption` ({id, name}); у части записей — строкой. */
export function creatureTypeName(entry: CompendiumEntry | undefined): string | null {
  const raw = entry?.data?.creature_type as { name?: unknown } | string | undefined;
  if (typeof raw === "string") return raw.trim() || null;
  if (raw && typeof raw === "object" && typeof raw.name === "string") return raw.name.trim() || null;
  return null;
}

function resolveType(type: string | null | undefined): string | null {
  if (!type) return null;
  const key = normType(type);
  const direct = Object.keys(SHAPES).find((k) => normType(k) === key);
  if (direct) return direct;
  return ALIASES[key.replace(/[^a-z]/g, "")] ?? null;
}

/** Знак типа. Тип не назван или незнаком — знака нет вовсе (§1.11: блоку,
 *  которому нечего показать, показывать нечего). Из 544 записей бестиария
 *  без типа девять. */
export function CreatureTypeBadge({ type, size = 19 }: { type: string | null | undefined; size?: number }) {
  const name = resolveType(type);
  if (!name) return null;
  const glyph = Math.round(size * (13 / 19));
  return (
    <span className="dnd-type-badge" style={{ width: size, height: size }} title={name}>
      <svg
        viewBox="0 0 24 24"
        width={glyph}
        height={glyph}
        fill="none"
        stroke="currentColor"
        strokeWidth={1.8}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
      >
        {SHAPES[name].map((s, i) =>
          "d" in s ? (
            <path key={i} d={s.d} />
          ) : "c" in s ? (
            <circle key={i} cx={s.c[0]} cy={s.c[1]} r={s.c[2]} />
          ) : (
            <ellipse key={i} cx={s.e[0]} cy={s.e[1]} rx={s.e[2]} ry={s.e[3]} />
          )
        )}
      </svg>
    </span>
  );
}
