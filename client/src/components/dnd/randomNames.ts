/** Случайное имя для вида (name_original); незнакомый вид — из людей. */
export function randomName(speciesOriginal: string | null | undefined, rnd: () => number = Math.random): string {
  const list = RANDOM_NAMES[speciesOriginal ?? ""] ?? RANDOM_NAMES.Human;
  const all = [...list.male, ...list.female, ...(list.nick ?? [])];
  return all[Math.floor(rnd() * all.length)];
}
